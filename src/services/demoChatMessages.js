/**
 * 방의 시연용 더미 메시지 목록을 오래된 순서로 돌려준다 (없으면 빈 배열).
 * 시각은 호출 시점 기준 "몇 분 전"이라 항상 최근 대화처럼 보인다.
 */
export function getDemoMessages(roomId) {
  if (!SHOW_DEMO_CHAT_MESSAGES) return [];
  const script = SCRIPTS[roomId];
  if (!script) return [];
  const now = Date.now();
  return script.map(([who, text, minutesAgo], i) => ({
    id: `demo-${roomId}-${i}`,
    senderId: `demo-${roomId}-${who}`,
    senderName: `익명${who}`,
    text,
    file: null,
    createdAt: now - minutesAgo * MIN,
    isDemo: true,
  }));
}
